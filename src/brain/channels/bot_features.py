# ---------------------------------------------------------------------------
# REMINDER SCHEDULER
# ---------------------------------------------------------------------------
class ReminderScheduler:
    """Sends a reminder message if the user has been inactive for N hours."""

    INACTIVITY_HOURS = 72  # 3 days
    CHECK_INTERVAL_SECONDS = 3600  # check every hour

    def __init__(self, api, state, owner):
        self.api = api
        self.state = state
        self.owner = owner
        self._stop = threading.Event()
        self._thread = threading.Thread(
            target=self._loop, name='brain-reminders', daemon=True
        )

    def start(self):
        self._thread.start()
        log.info('ReminderScheduler started (inactivity threshold: %dh)', self.INACTIVITY_HOURS)

    def stop(self):
        self._stop.set()

    def _loop(self):
        import random
        while not self._stop.is_set():
            self._stop.wait(self.CHECK_INTERVAL_SECONDS)
            if self._stop.is_set():
                break
            try:
                last_active = self.state.get('last_activity')
                if last_active is None:
                    continue
                elapsed_hours = (time.time() - float(last_active)) / 3600
                reminder_sent = self.state.get('reminder_sent_at')
                if reminder_sent:
                    since_reminder = (time.time() - float(reminder_sent)) / 3600
                    if since_reminder < self.INACTIVITY_HOURS:
                        continue
                if elapsed_hours >= self.INACTIVITY_HOURS and self.owner:
                    msg = random.choice(REMINDER_MESSAGES)
                    self.api.send(int(self.owner), msg)
                    self.state.put('reminder_sent_at', str(time.time()))
                    log.info('Sent inactivity reminder to owner.')
            except Exception:
                log.exception('Reminder scheduler error.')


def format_prompt_library_category(category_key: str) -> str:
    """Format a prompt library category for display."""
    prompts = PROMPT_LIBRARY.get(category_key, [])
    label = PROMPT_LIBRARY_LABELS.get(category_key, category_key.capitalize())
    lines = [f'Библиотека промптов — {label}:', '']
    for i, p in enumerate(prompts, 1):
        short = p[:80] + '...' if len(p) > 80 else p
        lines.append(f'{i}. {short}')
    lines += ['', 'Напиши номер промпта чтобы получить полный текст, или выбери другую категорию.']
    return '\n'.join(lines)


def get_prompt_by_number(category_key: str, number: int) -> str | None:
    """Return a full prompt by 1-based index."""
    prompts = PROMPT_LIBRARY.get(category_key, [])
    if 1 <= number <= len(prompts):
        return prompts[number - 1]
    return None
